-- ========================================================
-- ORDER MANAGEMENT SCHEMA
-- ========================================================

-- 1. ORDERS TABLE
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_id UUID REFERENCES public.consumer_profiles(id) NOT NULL,
    total_amount NUMERIC NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending', -- pending, confirmed, shipped, delivered, cancelled
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. ORDER ITEMS TABLE
CREATE TABLE IF NOT EXISTS public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES public.orders(id) ON DELETE CASCADE NOT NULL,
    product_id BIGINT REFERENCES public.products(id) NOT NULL,
    farmer_id UUID REFERENCES public.farmer_profiles(id) NOT NULL, -- Denormalized for easy farmer queries
    quantity INT NOT NULL,
    price_at_purchase NUMERIC NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. RLS POLICIES

-- Enable RLS
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;

-- ORDERS POLICIES
-- Consumers can view their own orders
CREATE POLICY "Consumers view own orders" ON public.orders
    FOR SELECT USING (auth.uid() = consumer_id);

-- Consumers can insert their own orders
CREATE POLICY "Consumers create orders" ON public.orders
    FOR INSERT WITH CHECK (auth.uid() = consumer_id);

-- Farmers can view orders containing their products (Bit tricky, usually fulfilled by querying items)
