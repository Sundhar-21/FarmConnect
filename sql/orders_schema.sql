-- ORDER ITEMS POLICIES
-- Consumers view their own items (via order link)
CREATE POLICY "Consumers view own items" ON public.order_items
    FOR SELECT USING (
        EXISTS (
            SELECT 1 FROM public.orders WHERE orders.id = order_items.order_id AND orders.consumer_id = auth.uid()
        )
    );

-- Consumers insert items
CREATE POLICY "Consumers insert items" ON public.order_items
    FOR INSERT WITH CHECK (
        EXISTS (
            SELECT 1 FROM public.orders WHERE orders.id = order_items.order_id AND orders.consumer_id = auth.uid()
        )
    );

-- Farmers view items assigned to them
CREATE POLICY "Farmers view assigned items" ON public.order_items
    FOR SELECT USING (farmer_id = auth.uid());

